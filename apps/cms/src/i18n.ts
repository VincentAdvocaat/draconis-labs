export const cmsMessages = {nl: {...documentMessages.nl, ...uiNl}, en: {...documentMessages.en, ...uiEn}};
export type MessageKey = keyof typeof cmsMessages.nl;
export type UiMessage = {key: MessageKey; params?: Record<string, string | number>} | {literal: string};
export const message = (key: MessageKey, params?: Record<string, string | number>): UiMessage => ({key, params});
const codes: Record<UiLocale, Record<string,string>> = {nl: {ready:'gereed', failed:'mislukt', pending:'in afwachting', processing:'in verwerking', unknown:'onbekend', cleared:'vrijgegeven', blocked:'geblokkeerd', building:'wordt gebouwd', published:'gepubliceerd', conflict:'conflict'}, en: {ready:'ready',failed:'failed',pending:'pending',processing:'processing',unknown:'unknown',cleared:'cleared',blocked:'blocked',building:'building',published:'published',conflict:'conflict'}};
export const codeLabel = (locale: UiLocale, value: string) => codes[locale][value] ?? value;
export function formatUiMessage(locale: UiLocale, value: UiMessage): string {
  if ('literal' in value) return value.literal;
  return cmsMessages[locale][value.key].replace(/\{([A-Za-z]+)\}/g, (placeholder, key: string) => {
    const parameter = value.params?.[key];
    return parameter === undefined ? placeholder : ['rights','state'].includes(key) ? codeLabel(locale,String(parameter)) : String(parameter);
  });
}
export function createCmsTranslator(locale: UiLocale) {return {copy: cmsMessages[locale], text: (key: MessageKey, params?: Record<string,string|number>) => formatUiMessage(locale,message(key,params)), code: (value: string) => codeLabel(locale,value)};}
export function apiErrorMessage(status: number, body: unknown, fallback: MessageKey = 'requestStatus'): UiMessage {
  const input = body && typeof body === 'object' ? body as Record<string, unknown> : {};
  switch (input.errorCode) {
    case 'media_not_publishable': return message('mediaNotPublishable');
    case 'media_unavailable': return message('mediaUnavailable');
    case 'content_not_publishable': return message('contentNotPublishable');
    case 'active_version_changed': return message('publicationConflict');
    case 'interrupted': return message('buildingInterrupted');
    case 'build_failed': return message('buildFailed');
  }
  const detail = typeof input.message === 'string' ? input.message : typeof input.errorCode === 'string' ? input.errorCode : null;
  return detail ? {literal: detail.slice(0, 500)} : message(fallback, {status});
}
